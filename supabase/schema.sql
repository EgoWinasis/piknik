
-- Tabel respons ajakan piknik
CREATE TABLE IF NOT EXISTS public.picnic_responses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_name TEXT NOT NULL DEFAULT 'Tamu misterius',
  accepted BOOLEAN NOT NULL DEFAULT TRUE,
  preferred_date DATE,
  preferred_place TEXT NOT NULL DEFAULT 'Taman yang banyak bunga',

  -- Tambahan aktivitas piknik
  preferred_activity TEXT NOT NULL DEFAULT 'Makan bersama',

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Aktifkan Row Level Security
ALTER TABLE public.picnic_responses
ENABLE ROW LEVEL SECURITY;

-- Pengunjung anonim hanya boleh mengirim jawaban menerima ajakan
CREATE POLICY "Anyone can submit picnic response"
ON public.picnic_responses
FOR INSERT
TO anon
WITH CHECK (accepted = TRUE);
